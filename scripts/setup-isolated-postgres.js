/*
 * CI-only schema bootstrap. It deliberately accepts only the explicitly named
 * ENGAGE_TEST_DATABASE_URL after the fail-closed isolation assertion passes.
 */
const { readFile } = require('node:fs/promises');
const path = require('node:path');
const pg = require('pg');
const { assertIsolatedTestDatabase } = require('./assert-isolated-test-db');

async function main() {
  assertIsolatedTestDatabase();
  const pool = new pg.Pool({ connectionString: process.env.ENGAGE_TEST_DATABASE_URL });
  try {
    await pool.query(`
      CREATE SCHEMA IF NOT EXISTS auth;
      CREATE TABLE IF NOT EXISTS auth.users (id uuid PRIMARY KEY);
      DO $$ BEGIN CREATE ROLE anon NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
      DO $$ BEGIN CREATE ROLE authenticated NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END $$;
      CREATE TABLE IF NOT EXISTS property (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL,
        code text NOT NULL UNIQUE
      );
      CREATE TABLE IF NOT EXISTS "user" (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        "propertyId" integer NOT NULL REFERENCES property(id),
        name text NOT NULL,
        email text NOT NULL UNIQUE,
        role text NOT NULL DEFAULT 'FRONT_DESK',
        "isActive" boolean NOT NULL DEFAULT true
      );
    `);
    for (const file of ['auth.sql', 'property-access.sql', 'managed-workspace.sql', 'sample-workspaces.sql']) {
      await pool.query(await readFile(path.join(__dirname, '..', 'sql', file), 'utf8'));
    }
    process.stdout.write('Isolated Engage Stay PostgreSQL schema applied.\n');
  } finally {
    await pool.end();
  }
}

main().catch((error) => { console.error(error.message); process.exitCode = 1; });
