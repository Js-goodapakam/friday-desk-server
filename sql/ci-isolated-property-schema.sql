-- Minimal, synthetic-only prerequisite for the real managed-workspace migration.
-- These property columns follow src/prisma/contract.prisma (model Property).
-- Never run this file against Supabase or any shared database.
CREATE TABLE IF NOT EXISTS "property" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  code text NOT NULL UNIQUE,
  city text,
  state text,
  country text NOT NULL DEFAULT 'India',
  timezone text NOT NULL DEFAULT 'Asia/Kolkata',
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);
